# ---------------------------------------------------------------------------
# 新词发现（互信息 + 左右邻接熵）
# ---------------------------------------------------------------------------

def discover_words(texts: Iterable[str], min_freq: int = 5,
                   max_len: int = 4, min_mi: float = 6.0,
                   top_n: int = 200) -> list[tuple[str, float]]:
    """从语料中自动发现候选新词。

    做法：
    1. 统计 1~max_len 字符片段的频次与左右邻接字符分布；
    2. 用互信息 (MI) 衡量内部凝聚度，用左右熵 (min) 衡量边界自由度；
    3. 综合打分 ``score = MI + min(左熵, 右熵)``，取 top_n。
    """
    n_gram_counter: dict[str, Counter] = defaultdict(Counter)
    for text in texts:
        text = re.sub(r"[\s，。！？、；：""''（）《》【】,.!?;:()\"]+", "", text)
        if not text:
            continue
        for n in range(1, max_len + 1):
            counter = n_gram_counter[n]
            for i in range(len(text) - n + 1):
                counter[text[i:i + n]] += 1

    total = sum(n_gram_counter[1].values()) or 1
    scored: list[tuple[str, float]] = []

    # 只考察长度 >= 2 的片段
    for n in range(2, max_len + 1):
        counter = n_gram_counter[n]
        for word, count in counter.items():
            if count < min_freq:
                continue
            # 互信息：P(whole) / prod(P(char_i))
            prob = count / total
            denom = 1.0
            for ch in word:
                denom *= (n_gram_counter[1].get(ch, 1) / total)
            mi = math.log(prob / denom, 2) if denom > 0 else 0.0
            if mi < min_mi:
                continue
            # 左右邻接熵
            left = Counter()
            right = Counter()
            for text in texts:
                text = re.sub(r"[\s，。！？、；：""''（）《》【】,.!?;:()\"]+", "", text)
                start = 0
                while True:
                    pos = text.find(word, start)
                    if pos < 0:
                        break
                    if pos > 0:
                        left[text[pos - 1]] += 1
                    if pos + len(word) < len(text):
                        right[text[pos + len(word)]] += 1
                    start = pos + 1
            left_entropy = _entropy(left)
            right_entropy = _entropy(right)
            # 纯数字/英文片段过滤
            if not any("一" <= c <= "鿿" for c in word):
                continue
            score = mi + min(left_entropy, right_entropy)
            scored.append((word, round(score, 4)))

    scored.sort(key=lambda x: x[1], reverse=True)
    return scored[:top_n]


def _entropy(counter: Counter) -> float:
    total = sum(counter.values())
    if total == 0:
        return 0.0
    ent = 0.0
    for count in counter.values():
        p = count / total
        ent -= p * math.log(p, 2)
    return ent
