def load_dictionary() -> dict:
    """返回分词词典（词 -> 频率）。

    优先尝试加载 jieba 的内置词典作为额外数据源（若安装），
    以提升分词覆盖率；算法本身不依赖 jieba。
    """
    freq = dict(CORE_DICTIONARY)
    try:
        import jieba
        jieba.initialize()
        for word, count in getattr(jieba, "FREQ", {}).items():
            freq[word] = max(freq.get(word, 0), count)
    except Exception:
        # jieba 未安装或初始化失败，使用内置词典即可
        pass
    return freq


